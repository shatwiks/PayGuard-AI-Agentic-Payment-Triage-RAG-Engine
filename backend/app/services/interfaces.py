"""Internal service interface contracts and protocols for PayGuard AI.

Defines the explicit, safe boundaries between the data-access layer,
deterministic triage engine, pgvector RAG retriever, LLM reasoning service,
and investigation orchestrator.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional
import uuid

from backend.app.schemas.common import PaginatedResponse, PaginationParams
from backend.app.schemas.payment import (
    PaymentDetailResponse,
    PaymentEventResponse,
    PaymentFilterParams,
    PaymentSummaryResponse,
)
from backend.app.schemas.investigation import (
    InvestigationCaseResponse,
    InvestigationCreateRequest,
    PolicyCitation,
)
from backend.app.schemas.auth import UserResponse


@dataclass(frozen=True)
class TriageClassificationResult:
    """Output of the deterministic triage classification engine."""
    category: str  # failed_payment, pending_payment, duplicate_charge, refund_status, unknown_or_other
    confidence_score: float
    rule_id_matched: Optional[str] = None
    identified_failure_code: Optional[str] = None
    is_ambiguous: bool = False
    missing_fields: List[str] = field(default_factory=list)
    recommended_action: str = "ESCALATE_TO_ANALYST"
    recommended_action_details: str = "Review transaction records manually."
    conflicting_evidence: List[str] = field(default_factory=list)
    supporting_record_ids: List[str] = field(default_factory=list)



@dataclass(frozen=True)
class LLMInvestigationOutput:
    """Output generated by the LLM reasoning layer, strictly grounded in verified facts."""
    investigation_summary: str
    recommended_action: str
    recommended_action_details: str
    missing_or_conflicting_info: List[str] = field(default_factory=list)
    human_review_required: bool = False
    human_review_reason: Optional[str] = None
    model_name: str = "gpt-4o-mini"
    likely_cause: Optional[str] = None
    generation_mode: str = "deterministic_fallback"
    cited_chunks: List[PolicyCitation] = field(default_factory=list)



class IPaymentService(ABC):
    """Read-only payment data access interface enforcing query limits and parameterization."""

    @abstractmethod
    async def get_payment_details(self, payment_id: uuid.UUID) -> Optional[PaymentDetailResponse]:
        """Fetch complete transaction details including gateway metadata and status."""
        pass

    @abstractmethod
    async def get_payment_by_reference(self, reference: str) -> Optional[PaymentDetailResponse]:
        """Look up payment by external reference string (e.g., tx_20261020_8841)."""
        pass

    @abstractmethod
    async def get_payment_history(self, payment_id: uuid.UUID) -> List[PaymentEventResponse]:
        """Retrieve chronological event and webhook timeline for a payment."""
        pass

    @abstractmethod
    async def search_payment_records(
        self,
        filters: PaymentFilterParams,
        pagination: PaginationParams,
    ) -> PaginatedResponse[PaymentSummaryResponse]:
        """Search payments with parameterized filters and bounded pagination."""
        pass


class ITriageEngine(ABC):
    """Deterministic payment triage engine using gateway failure codes and business rules."""

    @abstractmethod
    def classify_payment_issue(
        self,
        payment: Optional[PaymentDetailResponse],
        user_query: str,
    ) -> TriageClassificationResult:
        """Classify payment issue type deterministically without hallucination risks."""
        pass


class IRagService(ABC):
    """pgvector semantic and lexical retriever over indexed payment scheme policies."""

    @abstractmethod
    async def retrieve_troubleshooting_docs(
        self,
        query: str,
        issue_category: Optional[str] = None,
        top_k: int = 3,
    ) -> List[PolicyCitation]:
        """Retrieve authoritative policy excerpts with cosine distance ranking via pgvector."""
        pass


class ILLMReasoningService(ABC):
    """LLM synthesis layer grounded strictly in database facts and retrieved policy citations."""

    @abstractmethod
    async def generate_investigation_summary(
        self,
        user_query: str,
        payment: Optional[PaymentDetailResponse],
        citations: List[PolicyCitation],
        triage_result: TriageClassificationResult,
    ) -> LLMInvestigationOutput:
        """Generate structured explanation and recommended next steps using strictly bounded context."""
        pass


class IOrchestrationService(ABC):
    """Top-level investigation workflow orchestrator coordinating the entire triage pipeline."""

    @abstractmethod
    async def run_investigation(
        self,
        request: InvestigationCreateRequest,
        current_user: Optional[UserResponse] = None,
    ) -> InvestigationCaseResponse:
        """Execute end-to-end investigation pipeline: validate -> fetch -> triage -> rag -> llm -> audit -> persist."""
        pass


class IAuditService(ABC):
    """Audit logging interface for recording immutable operational traces and security events."""

    @abstractmethod
    async def log_audit_event(
        self,
        action: str,
        resource_type: str,
        resource_id: Optional[str] = None,
        user_id: Optional[uuid.UUID] = None,
        case_id: Optional[uuid.UUID] = None,
        details: Optional[Dict[str, Any]] = None,
        ip_address: Optional[str] = None,
    ) -> None:
        """Persist structured audit record."""
        pass

    @abstractmethod
    async def get_audit_events(
        self,
        case_id: Optional[uuid.UUID] = None,
        user_id: Optional[uuid.UUID] = None,
        limit: int = 50,
        offset: int = 0,
    ) -> List[Any]:
        """Retrieve audit events filtered by case or user."""
        pass
