"""Regenerate docs/PROJECT_METRICS.md with live codebase statistics.

Scans the repository and reports source size by language, test coverage
surface (test count), API surface (route count), migrations, and docs.
"""

import re
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "PROJECT_METRICS.md"

EXCLUDED_DIRS = {
    ".git", ".venv", "venv", "node_modules", ".next", "__pycache__",
    "storage", ".pytest_cache", "test-results", "playwright-report", ".agents",
}
LANGUAGES = {
    ".py": "Python",
    ".ts": "TypeScript",
    ".tsx": "TypeScript (React)",
    ".css": "CSS",
    ".sql": "SQL",
    ".md": "Markdown",
    ".yml": "YAML",
    ".yaml": "YAML",
}
ROUTE_PATTERN = re.compile(r"@(?:router|app)\.(get|post|put|patch|delete)\(")
TEST_PATTERN = re.compile(r"^\s*(?:async\s+)?def\s+test_", re.MULTILINE)


def iter_files():
    for path in ROOT.rglob("*"):
        if path.is_file() and not any(part in EXCLUDED_DIRS for part in path.relative_to(ROOT).parts):
            yield path


def main() -> None:
    files_by_lang = defaultdict(int)
    lines_by_lang = defaultdict(int)
    test_count = 0
    test_files = 0
    route_counts = defaultdict(int)
    migrations = 0

    for path in iter_files():
        lang = LANGUAGES.get(path.suffix.lower())
        if not lang:
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        files_by_lang[lang] += 1
        lines_by_lang[lang] += sum(1 for line in text.splitlines() if line.strip())

        rel = path.relative_to(ROOT).as_posix()
        if path.suffix == ".py":
            if path.name.startswith("test_"):
                found = len(TEST_PATTERN.findall(text))
                test_count += found
                test_files += 1 if found else 0
            for method in ROUTE_PATTERN.findall(text):
                route_counts[method.upper()] += 1
            if rel.startswith("alembic/versions/"):
                migrations += 1

    total_lines = sum(v for k, v in lines_by_lang.items() if k not in {"Markdown", "YAML"})
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    rows = "\n".join(
        f"| {lang} | {files_by_lang[lang]} | {lines_by_lang[lang]:,} |"
        for lang in sorted(files_by_lang, key=lambda k: -lines_by_lang[k])
    )
    routes = ", ".join(f"{m}: {c}" for m, c in sorted(route_counts.items())) or "n/a"

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        f"""# PayGuard AI — Project Metrics

_Auto-generated by `scripts/update_project_metrics.py`. Last refreshed: {now}._

## Summary

| Metric | Value |
|---|---|
| Source lines (non-blank, excl. docs/config) | {total_lines:,} |
| Test files | {test_files} |
| Test cases | {test_count} |
| API route handlers | {sum(route_counts.values())} ({routes}) |
| Alembic migrations | {migrations} |

## Codebase by Language

| Language | Files | Non-blank Lines |
|---|---|---|
{rows}
""",
        encoding="utf-8",
    )
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
